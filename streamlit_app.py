def fig_to_png_bytes(fig):
    """Convert a matplotlib figure to PNG bytes for st.download_button."""
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=200, bbox_inches="tight")
    buf.seek(0)
    return buf.getvalue()


