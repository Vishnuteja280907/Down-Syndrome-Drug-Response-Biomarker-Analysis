def render_biology_profile(protein_name):
    """Renders a 3-part protein profile: Normal Role -> Down Syndrome Problem ->
    Experiment's Discovery. The Discovery section only appears if the original
    study reported an actual finding for this protein; otherwise it's honestly
    omitted rather than filled with a guess."""
    profile = BIOLOGY_PROFILES.get(protein_name)
    if profile is None:
        st.caption("No curated biological note available yet for this protein.")
        return

    st.markdown(f"##### \U0001F9E0 Its Normal Role (Supporting Memory)")
    st.markdown(profile["role"])

    st.markdown(f"##### \u26A0\uFE0F The Down Syndrome Problem")
    st.markdown(profile["problem"])

    st.markdown(f"##### \U0001F52C The Experiment's Discovery")
    if profile["discovery"]:
        st.success("\u2713 A specific finding reported by the original study for this exact protein:")
        st.info(profile["discovery"])
    else:
        st.caption(
            "\u2139\ufe0f The original study did not report a specific finding for this "
            "protein -- the sections above are general background only."
        )


